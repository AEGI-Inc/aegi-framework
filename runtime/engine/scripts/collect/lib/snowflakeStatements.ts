/**
 * Snowflake 감사 로그 수집용 고정 SELECT 문 목록 (SNOW-90, SNOW-91, SNOW-92).
 *
 * HttpLayer 의 snowflake-log 읽기 POST 예외는 body.statement 가 이 얼린 배열의
 * 문자열과 글자까지 같을 때만 허용한다. 값은 bindings 로만 넣는다.
 */

export const SNOWFLAKE_SQL = {
  /** SNOW-90: 로그인 이력 */
  loginHistory:
    'SELECT EVENT_ID, TO_VARCHAR(CONVERT_TIMEZONE(\'UTC\', EVENT_TIMESTAMP), \'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"\') AS EVENT_TIMESTAMP, EVENT_TYPE, USER_NAME, CLIENT_IP, REPORTED_CLIENT_TYPE, FIRST_AUTHENTICATION_FACTOR, SECOND_AUTHENTICATION_FACTOR, IS_SUCCESS, ERROR_CODE, ERROR_MESSAGE, AUTHORIZING_INTEGRATION_NAME FROM snowflake.account_usage.login_history WHERE EVENT_TIMESTAMP >= TO_TIMESTAMP_TZ(?) AND EVENT_TIMESTAMP < TO_TIMESTAMP_TZ(?) ORDER BY EVENT_TIMESTAMP ASC LIMIT 10000',
  /** SNOW-91: 쿼리 이력 (QUERY_TEXT, ERROR_MESSAGE, BIND_VALUES, QUERY_TAG 제외) */
  queryHistory:
    'SELECT QUERY_ID, QUERY_TYPE, SESSION_ID, USER_NAME, ROLE_NAME, WAREHOUSE_NAME, DATABASE_NAME, SCHEMA_NAME, EXECUTION_STATUS, ERROR_CODE, TO_VARCHAR(CONVERT_TIMEZONE(\'UTC\', START_TIME), \'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"\') AS START_TIME, ROWS_UNLOADED FROM snowflake.account_usage.query_history WHERE START_TIME >= TO_TIMESTAMP_TZ(?) AND START_TIME < TO_TIMESTAMP_TZ(?) AND UPPER(USER_NAME) NOT IN (\'SYSTEM\', UPPER(CURRENT_USER())) AND (QUERY_TYPE IN (\'GRANT\', \'REVOKE\', \'UNLOAD\', \'COPY\') OR ((QUERY_TYPE LIKE \'CREATE%\' OR QUERY_TYPE LIKE \'ALTER%\' OR QUERY_TYPE LIKE \'DROP%\') AND QUERY_TYPE <> \'ALTER_SESSION\')) ORDER BY START_TIME ASC LIMIT 10000',
  /** SNOW-92: 사용자 역할 부여·회수 이력 */
  grantsToUsers:
    'SELECT TO_VARCHAR(CONVERT_TIMEZONE(\'UTC\', CREATED_ON), \'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"\') AS CREATED_ON, TO_VARCHAR(CONVERT_TIMEZONE(\'UTC\', DELETED_ON), \'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"\') AS DELETED_ON, ROLE, GRANTED_TO, GRANTEE_NAME, GRANTED_BY FROM snowflake.account_usage.grants_to_users WHERE (CREATED_ON >= TO_TIMESTAMP_TZ(?) AND CREATED_ON < TO_TIMESTAMP_TZ(?)) OR (DELETED_ON >= TO_TIMESTAMP_TZ(?) AND DELETED_ON < TO_TIMESTAMP_TZ(?)) ORDER BY COALESCE(DELETED_ON, CREATED_ON) ASC LIMIT 10000',
} as const

export const SNOWFLAKE_LOG_STATEMENTS: readonly string[] = Object.freeze([
  SNOWFLAKE_SQL.loginHistory,
  SNOWFLAKE_SQL.queryHistory,
  SNOWFLAKE_SQL.grantsToUsers,
])
